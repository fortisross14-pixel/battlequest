/** The age whose General Pack holds a general. */
export function generalPackAge(g: GeneralEntry): number {
  return g.packAge ?? g.age;
}

/** Generic generals (Common and Uncommon) are granted when their age opens, never drawn. */
export function isGeneric(g: GeneralEntry): boolean {
  return g.rarity === 'common' || g.rarity === 'uncommon';
}
